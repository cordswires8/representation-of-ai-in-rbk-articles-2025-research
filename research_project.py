import re
from razdel import sentenize
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification
from scipy.signal import savgol_filter

def clean_text(text: str) -> str:
    text = text.replace('\n', ' ')
    cleaned_text = re.sub(r'\s+', ' ', text).strip()
    return cleaned_text

my_texts = []

for text in rbc_articles['Text']:
  if 'ИИ' in text or 'искусственный интеллект' in text.lower() or 'искусственного интеллекта' in text.lower() or 'искусственному интеллекту' in text.lower() or 'искусственным интеллектом' in text.lower() or 'искусственном интеллекте' in text.lower() or 'ai' in text.lower() or 'llm' in text.lower():
    cleaned_text = clean_text(str(text))
    my_texts.append(cleaned_text)
  else:
    continue

print(len(my_texts))

model_checkpoint = 'cointegrated/rubert-tiny-sentiment-balanced'
tokenizer = AutoTokenizer.from_pretrained(model_checkpoint)
model = AutoModelForSequenceClassification.from_pretrained(model_checkpoint)
if torch.cuda.is_available():
    model.cuda()

def estimate_sentiment(messages: list) -> list:
    sentiment_out = []
    for text in messages:
        with torch.no_grad():
            inputs = tokenizer(text, return_tensors='pt', truncation=True, padding=True).to(model.device)
            proba = torch.sigmoid(model(**inputs).logits).cpu().numpy()[0]
            sentiment_out.append(proba.dot([-1, 0, 1]))
    return sentiment_out

sentiments = estimate_sentiment(my_texts)

filtered_sentiments = savgol_filter(sentiments, window_length=len(sentiments)//15, polyorder=0)

def ensemble_filter(data: list, n_filters=50, polyorder=0, **savgol_args) -> list:
    filt = 0
    start = len(data)//10
    stop = len(data)//4
    step = (stop-start)//n_filters
    if step == 0:
        step = 1
    for window_size in range(start, stop, step):
        res = savgol_filter(data, window_length=window_size, polyorder=polyorder, **savgol_args)
        filt += res
    return filt/n_filters

filtered_sentiments = ensemble_filter(sentiments, polyorder=0)
plt.figure(dpi=150)
